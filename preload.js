const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('ametra', {
  minimize: () => ipcRenderer.send('win:min'),
  close: () => ipcRenderer.send('win:close'),
  play: (opts) => ipcRenderer.invoke('play', opts),
  versions: () => ipcRenderer.invoke('versions:list'),
  clientMods: (id) => ipcRenderer.invoke('client:mods', id),
  toggleMod: (o) => ipcRenderer.invoke('client:toggle', o),
  syncMods: (o) => ipcRenderer.invoke('client:sync', o),
  saveConfig: (id, config) => ipcRenderer.invoke('client:config', { id, config }),
  modStatus: () => ipcRenderer.invoke('mod:status'),
  readConfig: (id) => ipcRenderer.invoke('client:readConfig', id),
  optPlan: (version) => ipcRenderer.invoke('opt:plan', version),
  optInstall: (o) => ipcRenderer.invoke('opt:install', o),
  loginMs: (silent) => ipcRenderer.invoke('login:ms', !!silent),
  openSkin: () => ipcRenderer.send('skin:open'),
  openUrl: (u) => ipcRenderer.send('open:url', u),
  serverStatus: (host) => ipcRenderer.invoke('server:status', host),
  partnersGet: () => ipcRenderer.invoke('partners:get'),
  partnersSave: (list) => ipcRenderer.invoke('partners:save', list),
  partnersReset: () => ipcRenderer.invoke('partners:reset'),
  partnersExport: () => ipcRenderer.invoke('partners:export'),
  devStatus: () => ipcRenderer.invoke('dev:status'),
  devSetPassword: (pw) => ipcRenderer.invoke('dev:setPassword', pw),
  devLogin: (pw) => ipcRenderer.invoke('dev:login', pw),
  devLogout: () => ipcRenderer.invoke('dev:logout'),
  pickSkin: () => ipcRenderer.invoke('skin:pick'),
  uploadSkin: (variant) => ipcRenderer.invoke('skin:upload', variant),
  saveLocalSkin: (variant) => ipcRenderer.invoke('skin:local', variant),
  clearLocalSkin: () => ipcRenderer.invoke('skin:localClear'),
  addMods: (id) => ipcRenderer.invoke('mods:add', id),
  openMods: (id) => ipcRenderer.invoke('mods:open', id),
  studioOpen: () => ipcRenderer.invoke('studio:open'),
  lbgList: () => ipcRenderer.invoke('lbg:list'),
  lbgAdd: () => ipcRenderer.invoke('lbg:add'),
  lbgOpen: () => ipcRenderer.invoke('lbg:open'),
  lbgRead: (name) => ipcRenderer.invoke('lbg:read', name),
  lbgRemove: (name) => ipcRenderer.invoke('lbg:remove', name),
  openBackgrounds: (id) => ipcRenderer.invoke('bg:open', id),
  bedrockPlay: (srv) => ipcRenderer.invoke('bedrock:launch', srv),
  bedrockImport: () => ipcRenderer.invoke('bedrock:import'),
  bedrockAmetra: () => ipcRenderer.invoke('bedrock:ametra'),
  bedrockList: () => ipcRenderer.invoke('bedrock:list'),
  bedrockRemove: (o) => ipcRenderer.invoke('bedrock:remove', o),
  bedrockBackup: (dir) => ipcRenderer.invoke('bedrock:backup', dir),
  bedrockFolder: () => ipcRenderer.invoke('bedrock:folder'),
  modsMeta: (slugs, version) => ipcRenderer.invoke('mods:meta', { slugs, version }),
  modsSearch: (o) => ipcRenderer.invoke('mods:search', o),
  modsList: (id) => ipcRenderer.invoke('mods:list', id),
  modsEnable: (o) => ipcRenderer.invoke('mods:enable', o),
  modsRemove: (o) => ipcRenderer.invoke('mods:remove', o),
  shotsOpen: (id) => ipcRenderer.invoke('shots:open', id),
  acctInfo: () => ipcRenderer.invoke('acct:info'),
  acctRegister: (u, p) => ipcRenderer.invoke('acct:register', u, p),
  acctLogin: (u, p) => ipcRenderer.invoke('acct:login', u, p),
  acctRestore: () => ipcRenderer.invoke('acct:restore'),
  acctLogout: () => ipcRenderer.invoke('acct:logout'),
  acctCall: (route, body) => ipcRenderer.invoke('acct:call', route, body),
  on: (channel, fn) => ipcRenderer.on(channel, (_e, data) => fn(data))
});
